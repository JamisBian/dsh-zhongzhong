const ALIAS_TO_HERB = new Map()
for (const [herb, aliases] of Object.entries(HERB_ALIASES)) {
  for (const alias of aliases) if (!ALIAS_TO_HERB.has(alias)) ALIAS_TO_HERB.set(alias, herb)
}

/** 按长度降序，后缀匹配用。 */
export const HERB_ALIAS_LIST = [...ALIAS_TO_HERB.keys()].sort((a, b) => b.length - a.length || a.localeCompare(b, 'zh'))

/**
 * 把原文里的药名 token 归一成标准药名。
 * @param {string} token
 * @returns {{herb:string, alias:string, prefix:string}|undefined}
 */
export function canonicalHerb(token) {
  if (typeof token !== 'string' || token === '') return undefined
  const exact = ALIAS_TO_HERB.get(token)
  if (exact !== undefined) return { herb: exact, alias: token, prefix: '' }
  for (const alias of HERB_ALIAS_LIST) {
    if (token.endsWith(alias) && token.length > alias.length) {
      return { herb: ALIAS_TO_HERB.get(alias), alias, prefix: token.slice(0, token.length - alias.length) }
    }
  }
  return undefined
}

